using System.Text.Json;
using OpenTail.Bullshark.Core.Activity;
using Xunit;

namespace OpenTail.Bullshark.Core.Tests.Activity;

/// <summary>
/// The line a resumed session starts with (D-L8), the first real message when a session opens with commands (plan question 6),
/// and the titles of a resumed session. Synthetic records only.
/// </summary>
public sealed class TranscriptLineageTests
{
    private const string Continued = "17a94483-99fc-4005-9fa9-dbd63958653d";
    private const string Other = "8aed1196-caaa-4c13-81ea-f2ef607248f5";

    private static string User(string text) =>
        "{\"type\":\"user\",\"timestamp\":\"2026-11-16T10:00:00Z\",\"message\":{\"role\":\"user\",\"content\":" +
        JsonSerializer.Serialize(text) + "}}";

    [Fact]
    public void TheContinuesLineIsRead()
    {
        var start = "Continues session: " + Continued + "\n\nThis session continues an earlier Claude Code session that had gone cold.";

        var summary = TranscriptReader.Summarize([User(start)]);

        Assert.Equal(Continued, summary.ContinuesSessionId);
    }

    [Fact]
    public void ALineLikeItLaterInTheSessionIsIgnored()
    {
        var summary = TranscriptReader.Summarize([User("Build the rail"), User("Continues session: " + Other)]);

        Assert.Null(summary.ContinuesSessionId);
    }

    [Fact]
    public void ACaveatIsNotTheFirstMessage()
    {
        // A session that opens with /model: the caveat, the command and its output are not what the owner wrote.
        var lines = new[]
        {
            User("<local-command-caveat>Caveat: the messages below were generated by the user while running local commands.</local-command-caveat>"),
            User("<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>"),
            User("<local-command-stdout>Set model to opus</local-command-stdout>"),
            User("Write the plan"),
        };

        var summary = TranscriptReader.Summarize(lines);

        Assert.Equal("Write the plan", summary.FirstUserText);
    }

    [Fact]
    public void AResumedSessionHasNoTitleFromItsStartText()
    {
        Assert.Null(SessionTitle.Clean("Continues session: " + Continued + "\n\nThis session continues an earlier Claude Code session."));
        Assert.Null(SessionTitle.Clean("This session continues an earlier Claude Code session that had gone cold."));
    }
}
